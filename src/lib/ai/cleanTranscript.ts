// Чистка устной речи без модели: работает и в браузере («оставить как сказал»), и на сервере.
// Слова-паразиты устной речи: убираем, только если они стоят отдельным словом.
const FILLERS = ['ну', 'короче', 'короче говоря', 'типа', 'как бы', 'в общем', 'вообще-то', 'эээ', 'ээ', 'э', 'ммм', 'мм', 'значит', 'вот', 'это самое', 'так сказать', 'получается'];

/**
 * Запасной путь без модели: чистим расшифровку браузера сами.
 * Убираем паразитов и повторы, ставим заглавные буквы и точки — смысл и слова человека не трогаем.
 */
export function cleanTranscript(raw: string): string {
  let t = ` ${raw.replace(/\s+/g, ' ').trim()} `;
  for (const f of [...FILLERS].sort((a, b) => b.length - a.length)) {
    // Дважды: соседние паразиты («ну короче») делят один пробел, и второй за один проход не ловится.
    const re = new RegExp(`(^|[\\s,.!?])${f}(?=[\\s,.!?]|$)`, 'giu');
    t = t.replace(re, '$1').replace(re, '$1');
  }
  t = t
    // «мы мы пошли» → «мы пошли». \b в JS не считает кириллицу буквами, поэтому границы — явные.
    .replace(/(^|[^\p{L}])(\p{L}+)(?:\s+\2)+(?=[^\p{L}]|$)/giu, '$1$2')
    .replace(/\s+([,.!?])/g, '$1')
    .replace(/([,.!?])(?=[^\s])/g, '$1 ')
    .replace(/,\s*([.!?])/g, '$1')
    .replace(/^[\s,.]+/, '')
    .replace(/\s{2,}/g, ' ')
    .trim();
  if (!t) return '';
  // Предложения с заглавной, в конце точка.
  t = t.replace(/(^|[.!?]\s+)(\p{Ll})/gu, (_, p: string, c: string) => p + c.toLocaleUpperCase('ru'));
  if (!/[.!?…]$/.test(t)) t += '.';
  return t;
}
